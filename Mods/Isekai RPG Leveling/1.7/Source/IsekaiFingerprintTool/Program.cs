using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Text;

namespace NoobsFixes.IsekaiLevelingFix
{
	/// <summary>
	/// Records what the anchored Isekai methods look like, so the mod can tell at startup whether
	/// it is looking at the code its fixes were written against (apply), a build that already has
	/// the fixes (skip), or code that changed since (pause).
	///
	///   IsekaiFingerprintTool --upstream &lt;Workshop IsekaiLeveling.dll&gt;
	///                         [--fixed &lt;fork IsekaiLeveling.dll&gt;]
	///                         --out &lt;...\Core\KnownFingerprints.Generated.cs&gt;
	///                         [--dump &lt;folder&gt;]    (writes the normalized IL per method, for diffing)
	/// </summary>
	internal static class Program
	{
		private static int Main(string[] args)
		{
			string upstream = Arg(args, "--upstream");
			string fixedBuild = Arg(args, "--fixed");
			string output = Arg(args, "--out");
			string dump = Arg(args, "--dump");
			if (upstream == null || output == null)
			{
				Console.Error.WriteLine("usage: IsekaiFingerprintTool --upstream <dll> [--fixed <dll>] --out <file.cs> [--dump <folder>]");
				return 2;
			}

			var anchors = Anchors.All().OrderBy(a => a.Key, StringComparer.Ordinal).ToList();
			var upstreamFp = new Dictionary<string, string>();
			var forkSameCodeFp = new Dictionary<string, string>();
			var fixedFp = new Dictionary<string, string>();
			int errors = 0;

			using (var up = new MetadataFingerprinter(File.ReadAllBytes(upstream)))
			using (var fx = fixedBuild != null ? new MetadataFingerprinter(File.ReadAllBytes(fixedBuild)) : null)
			{
				foreach (Anchor a in anchors)
				{
					if (!up.TryFingerprint(a, out string u, out string err))
					{
						Console.Error.WriteLine("UPSTREAM MISSING  " + a.Key + ": " + err);
						errors++;
						continue;
					}
					upstreamFp[a.Key] = u;
					string status = "same in both";
					if (fx != null)
					{
						if (fx.TryFingerprint(a, out string f, out string ferr))
						{
							if (f != u && a.SameCodeInFork)
							{
								forkSameCodeFp[a.Key] = f;
								status = "fork build differs, same source: recorded as upstream";
							}
							else if (f != u)
							{
								fixedFp[a.Key] = f;
								status = "CHANGED in fixed build";
							}
						}
						else status = "missing in fixed build (" + ferr + ")";
					}
					Console.WriteLine(u + "  " + a.Display.PadRight(55) + status);

					if (dump != null)
					{
						Directory.CreateDirectory(dump);
						string name = a.Key.Replace("::", "__").Replace('/', '_').Replace('+', '_');
						if (up.TryDescribe(a, out string ut, out _)) File.WriteAllText(Path.Combine(dump, name + ".upstream.txt"), ut);
						if (fx != null && fx.TryDescribe(a, out string ft, out _)) File.WriteAllText(Path.Combine(dump, name + ".fixed.txt"), ft);
					}
				}
			}

			if (errors > 0)
			{
				Console.Error.WriteLine(errors + " anchor(s) do not exist in the upstream build; fix Anchors.cs first. Nothing written.");
				return 1;
			}

			string source = Describe(upstream);
			var sb = new StringBuilder();
			sb.AppendLine("// <auto-generated>");
			sb.AppendLine("//   Written by Source\\IsekaiFingerprintTool. Do not edit by hand; re-run the tool instead.");
			sb.AppendLine("//   Upstream: " + upstream + "  (" + source + ")");
			if (fixedBuild != null) sb.AppendLine("//   Fixed:    " + fixedBuild + "  (" + Describe(fixedBuild) + ")");
			sb.AppendLine("// </auto-generated>");
			sb.AppendLine("namespace NoobsFixes.IsekaiLevelingFix");
			sb.AppendLine("{");
			sb.AppendLine("\tinternal static partial class KnownFingerprints");
			sb.AppendLine("\t{");
			sb.AppendLine("\t\tstatic partial void Fill()");
			sb.AppendLine("\t\t{");
			sb.AppendLine("\t\t\tSource = \"" + source + "\";");
			sb.AppendLine();
			foreach (var kv in upstreamFp) sb.AppendLine("\t\t\tAdd(Upstream, \"" + kv.Key + "\", \"" + kv.Value + "\");");
			if (forkSameCodeFp.Count > 0)
			{
				sb.AppendLine("\t\t\t// Same source in the fixed build (fork), compiled differently:");
				foreach (var kv in forkSameCodeFp) sb.AppendLine("\t\t\tAdd(Upstream, \"" + kv.Key + "\", \"" + kv.Value + "\");");
			}
			if (fixedFp.Count > 0)
			{
				sb.AppendLine();
				foreach (var kv in fixedFp) sb.AppendLine("\t\t\tAdd(AlreadyFixed, \"" + kv.Key + "\", \"" + kv.Value + "\");");
			}
			sb.AppendLine("\t\t}");
			sb.AppendLine("\t}");
			sb.AppendLine("}");
			File.WriteAllText(output, sb.ToString().Replace("\r\n", "\n").Replace("\n", "\r\n"), new UTF8Encoding(false));
			Console.WriteLine("Wrote " + upstreamFp.Count + " upstream and " + fixedFp.Count + " fixed-build fingerprints to " + output);
			return 0;
		}

		private static string Arg(string[] args, string name)
		{
			int i = Array.IndexOf(args, name);
			return i >= 0 && i + 1 < args.Length ? args[i + 1] : null;
		}

		/// <summary>"IsekaiLeveling.dll build 1a2b3c4d, 2026-09-06": the MVID changes with every compile.</summary>
		private static string Describe(string path)
		{
			using (var pe = new PEReader(File.OpenRead(path)))
			{
				MetadataReader md = pe.GetMetadataReader();
				Guid mvid = md.GetGuid(md.GetModuleDefinition().Mvid);
				return Path.GetFileName(path) + " build " + mvid.ToString("N").Substring(0, 8) + ", " + File.GetLastWriteTime(path).ToString("yyyy-MM-dd");
			}
		}
	}
}
